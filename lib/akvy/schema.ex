defmodule Akvy.Schema do
  @moduledoc """
  Base schema for all Akvy tables.

  Primary keys are time-ordered UUIDv7 values generated by the application, which
  keeps B-tree indexes compact and allows keyset pagination by `id`.
  """

  @doc "Uses `Ecto.Schema` with UUIDv7 primary/foreign keys and `:utc_datetime_usec` timestamps."
  defmacro __using__(_opts) do
    quote do
      use Ecto.Schema

      @primary_key {:id, UUIDv7, autogenerate: true}
      @foreign_key_type UUIDv7
      @timestamps_opts [type: :utc_datetime_usec]
    end
  end
end
